import test from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import * as THREE from 'three';

const canvasContext=new Proxy({createLinearGradient:()=>({addColorStop(){}}),createRadialGradient:()=>({addColorStop(){}})},{get:(target,key)=>target[key]??(()=>{})});
globalThis.document={createElement:()=>({width:128,height:128,getContext:()=>canvasContext})};
const {LANDMARK_BUILDERS}=await import('../dist/landmark-models.js');
const {landmarks}=JSON.parse(await readFile(new URL('../dist/Data/landmarks.json',import.meta.url)));

test('Kaohsiung airport has one real-location stamp target and four distinguishable aircraft',()=>{
  const matches=landmarks.filter(item=>item.type==='kaohsiungAirport');
  assert.equal(matches.length,1);
  const site=matches[0];
  assert.equal(site.country,'台灣');
  assert.ok(site.lat>22.57&&site.lat<22.59&&site.lon>120.34&&site.lon<120.36);
  assert.ok(site.aliases.includes('小港機場'));
  assert.equal(site.seal,'小港機場');
  assert.equal(site.displayScale,.60);
  const model=LANDMARK_BUILDERS.kaohsiungAirport();
  const aircraft=[];model.traverse(o=>{if(o.userData.role==='airport-aircraft')aircraft.push(o);});
  assert.deepEqual(aircraft.map(o=>o.userData.operation).sort(),['landing','parked','parked','takeoff']);
  const takeoff=aircraft.find(o=>o.userData.operation==='takeoff');
  const landing=aircraft.find(o=>o.userData.operation==='landing');
  const parked=aircraft.filter(o=>o.userData.operation==='parked');
  const parkedPositions=parked.map(o=>o.position.clone());
  model.userData.update(2);
  assert.equal(takeoff.visible,true);assert.equal(landing.visible,false);
  assert.ok(takeoff.position.y>.085&&takeoff.rotation.z>0);
  const xAtTwo=takeoff.position.x;model.userData.update(3);
  assert.ok(takeoff.position.x>xAtTwo+.8,'takeoff crosses the runway quickly');
  model.userData.update(4.75);
  assert.equal(takeoff.visible,false);assert.equal(landing.visible,false);
  model.userData.update(6);
  assert.equal(takeoff.visible,false);assert.equal(landing.visible,true);
  assert.ok(landing.position.y>.085&&landing.rotation.z<0);
  const landingX=landing.position.x;model.userData.update(7);
  assert.ok(landing.position.x>landingX+.8,'landing approach moves quickly');
  model.userData.update(10);
  assert.equal(takeoff.visible,false);assert.equal(landing.visible,false);
  for(let i=0;i<parked.length;i++)assert.ok(parked[i].visible&&parked[i].position.equals(parkedPositions[i]));
  const bounds=new THREE.Box3().setFromObject(model);
  assert.ok(bounds.max.x-bounds.min.x>4);
  assert.ok(bounds.max.z-bounds.min.z>1);
});
